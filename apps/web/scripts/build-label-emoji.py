"""Build deterministic, compressed inline artwork from Twemoji v17.0.1.

Usage: python3 scripts/build-label-emoji.py /path/to/twemoji-17.0.1/assets/svg
Download: https://github.com/jdecked/twemoji/releases/tag/v17.0.1
Graphics: Twitter and other contributors, CC-BY-4.0 (see label-fonts).
Only static SVG geometry is retained; CSS is converted to presentation attributes.
"""
import base64
import hashlib
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET
import zlib

source = Path(sys.argv[1])
root = Path(__file__).resolve().parents[1]
allowed_tags = {"svg", "g", "path", "circle", "ellipse", "defs", "clipPath"}
allowed_attributes = {"viewBox", "d", "fill", "fill-rule", "clip-rule", "opacity", "fill-opacity", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "stroke-miterlimit", "stroke-opacity", "cx", "cy", "r", "rx", "ry", "transform", "clip-path", "clipPathUnits", "id"}
ET.register_namespace("", "http://www.w3.org/2000/svg")
data = {}
for file in sorted(source.glob("*.svg")):
    svg = ET.parse(file).getroot()
    styles = {}
    for node in svg.iter():
        if node.tag.endswith("}style"):
            for name, declarations in re.findall(r"\.([\w-]+)\s*\{([^}]+)\}", node.text or ""):
                styles[name] = dict(pair.strip().split(":", 1) for pair in declarations.split(";") if pair.strip())
    for parent in svg.iter():
        for child in list(parent):
            if child.tag.endswith("}style"):
                parent.remove(child)
    for node in svg.iter():
        tag = node.tag.split("}")[-1]
        assert tag in allowed_tags, (file.name, tag)
        for name in node.attrib.pop("class", "").split():
            node.attrib.update({key.strip(): value.strip() for key, value in styles[name].items()})
        node.attrib.pop("version", None)
        node.attrib.pop("{http://www.w3.org/XML/1998/namespace}space", None)
        for key, value in list(node.attrib.items()):
            assert key in allowed_attributes, (file.name, key)
            if key == "id":
                node.set(key, f"emoji-{file.stem}-{value}")
            elif "url(" in value:
                assert re.fullmatch(r"url\(#[\w-]+\)", value), (file.name, value)
                node.set(key, value.replace("url(#", f"url(#emoji-{file.stem}-"))
            assert not re.search(r"https?:|javascript:|data:", value, re.I), (file.name, value)
        node.text = None
        node.tail = None
    svg.attrib.pop("id", None)
    markup = ET.tostring(svg, encoding="unicode")
    key = "-".join(part for part in file.stem.split("-") if part != "fe0f")
    assert key not in data, key
    data[key] = markup
assert len(data) == 4009, "Use the pinned Twemoji v17.0.1 assets"
raw = json.dumps(data, separators=(",", ":")).encode()
license_file = source.parents[1] / "LICENSE-GRAPHICS"
(root / "lib/label-fonts/LICENSE_TWEMOJI.txt").write_text(license_file.read_text())
header = f"""/** @license Twemoji v17.0.1 graphics, Twitter and other contributors, CC-BY-4.0.
 * https://github.com/jdecked/twemoji — https://creativecommons.org/licenses/by/4.0/
 * Generated by scripts/build-label-emoji.py; static geometry, namespaced IDs, no external assets.
 * Unpacked SHA-256: {hashlib.sha256(raw).hexdigest()}
 */
"""
chunks = [{} for _ in range(64)]
for key, svg in data.items():
    bucket = sum(ord(character) for character in key) % len(chunks)
    chunks[bucket][key] = svg
directory = root / "lib/label-emoji-data"
directory.mkdir(exist_ok=True)
total = 0
for index, chunk in enumerate(chunks):
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    content = json.dumps(chunk, separators=(",", ":")).encode()
    packed = base64.b64encode(compressor.compress(content) + compressor.flush()).decode()
    total += len(packed)
    (directory / f"{index}.ts").write_text(header + 'const packed: string = "' + packed + '";\nexport default packed;\n')
loaders = ",\n".join(f'  () => import("./label-emoji-data/{index}.ts")' for index in range(len(chunks)))
(root / "lib/label-emoji-data.ts").write_text(header + 'export const labelEmojiIds = new Set("' + "|".join(data) + '".split("|"));\nexport const labelEmojiChunks: Array<() => Promise<{ default: string }>> = [\n' + loaders + '\n];\n')
print(f"Bundled {len(data)} emoji in {len(chunks)} demand-loaded chunks: {total} base64 bytes")
