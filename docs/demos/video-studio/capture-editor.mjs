// Capture the actual local editor with isolated fixture routes; start Relay on port3022 first.
import {createRequire} from 'node:module';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
const require=createRequire(new URL('../../../apps/web/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const [timelinePath=new URL('./editor-timeline.json',import.meta.url).pathname,out=new URL('.',import.meta.url).pathname]=process.argv.slice(2);
await mkdir(out,{recursive:true});
const timeline=JSON.parse(await readFile(timelinePath,'utf8'));
let project={id:'studio-showcase',name:'Relay motion showcase',caption:'',brandId:'',labels:[],revision:1,createdAt:'2026-10-08T00:00:00Z',updatedAt:'2026-10-08T00:00:00Z',timeline};
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1600,height:1050},deviceScaleFactor:1,recordVideo:{dir:'/private/tmp/relay-studio-recording',size:{width:1600,height:1050}}});
const page=await context.newPage(),errors=[];
page.setDefaultTimeout(15000);
page.on('pageerror',e=>errors.push(e.message));
await page.route('https://media.example.test/**',async r=>{
 const filename=path.basename(new URL(r.request().url()).pathname);
 const ext=path.extname(filename);
 const contentType=({'.mp4':'video/mp4','.png':'image/png','.svg':'image/svg+xml','.wav':'audio/wav','.jpg':'image/jpeg'})[ext]??'application/octet-stream';
 await r.fulfill({contentType,body:await readFile(path.join(out,filename))});
});
await page.route('**/api/v1/videos',r=>{
 if(r.request().method()==='PATCH'){project={...r.request().postDataJSON(),revision:project.revision+1};return r.fulfill({json:{data:project}});}
 return r.fulfill({json:{data:[project]}});
});
for(const part of ['videos/templates','brands/kit','videos/jobs*','media/projects','media?*'])await page.route(`**/api/v1/${part}`,r=>r.fulfill({json:{data:[]}}));
await page.route('**/api/v1/videos/compose',r=>r.fulfill({json:{data:{available:false}}}));
const started=Date.now();
await page.goto('http://127.0.0.1:3022/demo?view=videos');
await page.getByRole('button',{name:/^Relay motion showcase/}).click();
await page.locator('.unified-video-studio').evaluate(async el=>{await Promise.all(el.getAnimations().map(a=>a.finished));});
await page.evaluate(()=>document.fonts.ready);
await page.getByLabel('Timeline playhead',{exact:true}).fill('1800');
await page.locator('.unified-video-canvas img').first().waitFor({state:'visible'}).catch(()=>{});
await page.waitForTimeout(500);
await page.locator('.unified-video-studio').screenshot({path:path.join(out,'editor-workspace.png')});
const camera=page.getByRole('region',{name:'Camera & focus',exact:true});
if(await camera.locator('.video-camera-keyframes').count())await camera.getByText('Camera keyframes',{exact:false}).click();
await camera.getByLabel('Camera keyframe 1 easing',{exact:true}).selectOption('spring');
await camera.getByLabel('Camera keyframe 1 spring stiffness',{exact:true}).fill('180');
await camera.getByLabel('Camera keyframe 1 spring damping',{exact:true}).fill('18');
await camera.locator('.motion-spring-controls').first().evaluate(el=>el.scrollIntoView({block:'center'}));
await page.waitForTimeout(300);
await page.locator('.unified-video-studio').screenshot({path:path.join(out,'editor-curves.png')});
await camera.getByText('Camera keyframes',{exact:false}).click();
const scene=page.getByText('Studio scene',{exact:true});
await scene.evaluate(el=>el.scrollIntoView({block:'center'}));
await scene.click();
await page.getByLabel('Scene environment',{exact:true}).selectOption('softbox');
await scene.evaluate(el=>el.scrollIntoView({block:'start'}));
const overflow=await page.locator('.scene-controls').evaluate(el=>{const edge=el.getBoundingClientRect().right;return [...el.querySelectorAll('input,select,output')].filter(control=>control.getBoundingClientRect().right>edge+2).map(control=>control.getAttribute('aria-label')??control.tagName);});
if(overflow.length)throw new Error(`Scene controls overflow: ${overflow.join(', ')}`);
await page.waitForTimeout(300);
await page.locator('.unified-video-studio').screenshot({path:path.join(out,'editor-scene.png')});
await page.getByLabel('Timeline playhead',{exact:true}).fill('0');
const playStart=(Date.now()-started)/1000;
await page.getByRole('button',{name:'Play',exact:true}).click();
await page.waitForTimeout(Math.min(10000,timeline.clips.reduce((a,c)=>a+(c.outMs-c.inMs)/(c.speed??1),0)));
if(await page.getByRole('button',{name:'Pause',exact:true}).count())await page.getByRole('button',{name:'Pause',exact:true}).click();
await page.screenshot({path:path.join(out,'editor-playback-end.png')});
const videoPath=await page.video().path();
await context.close();await browser.close();
await writeFile(path.join(out,'capture-metadata.json'),JSON.stringify({errors,videoPath,playStart},null,2));
console.log(JSON.stringify({errors,videoPath,playStart}));
